// PreToolUse: block direct edits to lock files, env files and generated Tauri output.
let input = "";
for await (const chunk of process.stdin) input += chunk;
const path = (JSON.parse(input).tool_input?.file_path ?? "").replaceAll("\\", "/");

const rules = [
  [/(^|\/)package-lock\.json$/, "package-lock.json is managed by npm; run an npm command instead"],
  [/(^|\/)Cargo\.lock$/, "Cargo.lock is managed by cargo; run a cargo command instead"],
  [/(^|\/)\.env(\.|$)/, ".env files hold secrets and must not be edited by Claude"],
  [/(^|\/)src-tauri\/gen\//, "src-tauri/gen/ is generated by Tauri"],
];

for (const [re, reason] of rules) {
  if (re.test(path)) {
    console.error(`Blocked: ${reason} (${path})`);
    process.exit(2);
  }
}
